# 1. ARITHMETIC OPERATORS
a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)


# 2. COMPARISON OPERATORS
print(a > b)
print(a < b)
print(a == b)
print(a != b)


# 3. ASSIGNMENT OPERATORS
x = 5
x += 2
print("x =", x)


# 4. LOGICAL OPERATORS
print(a > 5 and b < 5)
print(a > 15 or b < 5)
print(not(a > b))


# 5. USER INPUT
num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

print("Sum:", num1 + num2)
